import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { functionPackageDigest, STAGED_RELEASE_FUNCTIONS } from "../base44_release_manifest.mjs";

export const STAGED_V9_ROUTES_FILE = "data/generated-staged-v9-routes.json";
export const FUNCTION_BUILD_ID_FILE = "generatedBuildId.js";

export function computeFunctionBuildId(files) {
  const hash = crypto.createHash("sha256");
  for (const file of [...files.keys()].sort()) {
    if (file === FUNCTION_BUILD_ID_FILE) continue;
    hash.update(file).update("\0").update(files.get(file)).update("\0");
  }
  return hash.digest("hex");
}

export function functionBuildIdSource(fnName, buildId) {
  return [
    "// DO NOT EDIT. Generated by scripts/generate_release_contracts.mjs.",
    `// SHA-256 package identity for base44/functions/${fnName}.`,
    `// Every regular package file is covered except ${FUNCTION_BUILD_ID_FILE} itself.`,
    "",
    `export const FUNCTION_BUILD_ID = ${JSON.stringify(buildId)};`,
    "",
  ].join("\n");
}

export function functionActivationId(source, name) {
  const marker = source.match(/BASE44_RUNTIME_ACTIVATION_ID\s*=\s*"([A-Za-z0-9._-]{1,120})"/);
  if (!marker) throw new Error(`Release Base44 function has no runtime activation marker: ${name}`);
  return marker[1];
}

function renderFunctionConfig(bytes, canonicalName, routeName) {
  if (!bytes) throw new Error(`Staged V9 package has no function.jsonc: ${canonicalName}`);
  const source = bytes.toString("utf8");
  const parse = text => JSON.parse(text.replace(/^\s*\/\/.*$/gm, ""));
  const config = parse(source);
  const pattern = new RegExp('("name"\\s*:\\s*")' + canonicalName + '(")', "g");
  if (!bytes.equals(Buffer.from(source)) || config?.name !== canonicalName || config.entry !== "entry.ts"
      || [...source.matchAll(pattern)].length !== 1) {
    throw new Error(`Invalid staged V9 function config: ${canonicalName}`);
  }
  const rendered = source.replace(pattern, `$1${routeName}$2`);
  if (parse(rendered).name !== routeName) throw new Error(`Could not rename staged V9 function: ${canonicalName}`);
  return Buffer.from(rendered);
}

export function renderStagedV9Packages(root) {
  const packages = new Map();
  const functions = {};
  for (const name of STAGED_RELEASE_FUNCTIONS) {
    const dir = path.join(root, "base44/functions", name);
    if (!fs.lstatSync(dir, { throwIfNoEntry: false })?.isDirectory()) {
      throw new Error(`Missing staged V9 function package: ${name}`);
    }
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    if (entries.some(entry => !entry.isFile())) throw new Error(`Invalid staged V9 package inventory: ${name}`);
    const files = new Map(entries.map(entry => [entry.name, fs.readFileSync(path.join(dir, entry.name))]));
    const canonicalBuild = computeFunctionBuildId(files);
    const route = `${name}B${canonicalBuild.slice(0, 16)}`;
    if (!/^[A-Za-z][A-Za-z0-9]{0,62}$/.test(route) || packages.has(route)) {
      throw new Error(`Invalid staged V9 route name: ${route}`);
    }
    const entry = files.get("entry.ts");
    if (!entry) throw new Error(`Staged V9 package has no entry.ts: ${name}`);
    const runtimeActivation = functionActivationId(entry.toString("utf8"), name);
    files.set("function.jsonc", renderFunctionConfig(files.get("function.jsonc"), name, route));
    const build = computeFunctionBuildId(files);
    files.set(FUNCTION_BUILD_ID_FILE, Buffer.from(functionBuildIdSource(route, build)));
    const sortedFiles = [...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const fileHashes = Object.fromEntries(sortedFiles.map(([file, bytes]) => [file, {
      sha256: crypto.createHash("sha256").update(bytes).digest("hex"),
    }]));
    functions[name] = {
      route_name: route,
      build_id: build,
      runtime_activation_id: runtimeActivation,
      package_digest: functionPackageDigest(fileHashes),
    };
    packages.set(route, sortedFiles);
  }
  return { contract: { schema_version: "fixlist_staged_v9_routes_v1", functions }, packages };
}

export function stagedV9RoutesSource(contract) {
  return `${JSON.stringify(contract, null, 2)}\n`;
}

export function materializeStagedV9Packages(root, output) {
  if (!path.isAbsolute(output)) throw new Error("Choose a new absolute staged V9 project directory.");
  const { contract, packages } = renderStagedV9Packages(root);
  if (fs.readFileSync(path.join(root, STAGED_V9_ROUTES_FILE), "utf8") !== stagedV9RoutesSource(contract)) {
    throw new Error("Generated staged V9 routes differ from package bytes. Run scripts/generate_release_contracts.mjs.");
  }
  fs.mkdirSync(output, { mode: 0o700 });
  try {
    const base = path.join(output, "base44");
    fs.mkdirSync(path.join(base, "functions"), { recursive: true });
    fs.mkdirSync(path.join(base, "entities"));
    fs.writeFileSync(path.join(base, "config.jsonc"), JSON.stringify({
      name: "fixlist-staged-candidate",
      functionsDir: "functions",
      entitiesDir: "entities",
    }) + "\n");
    for (const [route, files] of packages) {
      const dir = path.join(base, "functions", route);
      fs.mkdirSync(dir);
      for (const [file, bytes] of files) fs.writeFileSync(path.join(dir, file), bytes, { flag: "wx" });
    }
  } catch (error) {
    fs.rmSync(output, { recursive: true, force: true });
    throw error;
  }
}
