"""Patch C - the whole chain, not one seam.

The blueprint is explicit that a narrow unit test is not enough here: the point
of this patch is that a limited scan takes a *different persistence path*, and
that only shows up when scanner -> review -> worker envelope is exercised
together and then handed across the language boundary intact.

This half runs the real pipeline and regenerates
tests/fixtures/limited-result-end-to-end.json. The JavaScript half
(tests/frontend/limitedResultEndToEnd.test.mjs) consumes that exact file through
the Base44 persistence snapshot and the customer projection. Regenerating and
comparing here is what stops the fixture drifting away from the pipeline it
claims to represent.
"""
import json
from pathlib import Path

from app.coverage_authority import attach_coverage_authority_evidence
from app.evidence_quality import apply_evidence_quality_gate
from app.review import run_review
from app.scan_job import (
    LIMITED_COVERAGE_STATES,
    build_limited_envelope,
    coverage_state_of,
    terminal_review_limitation,
)

FIXTURE = Path(__file__).resolve().parents[2] / "tests" / "fixtures" / "limited-result-end-to-end.json"
SIGNING_KEY = "e2e-signing-key-never-deployed"


def _page(index: int) -> dict:
    return {
        "url": f"https://www.tanners-wines.co.uk/p{index}",
        "final_url": f"https://www.tanners-wines.co.uk/p{index}",
        "status_code": 200,
        "content_type": "text/html",
        "fetch_error": "",
        "page_evidence_class": "usable_html",
        "word_count": 350,
        "title": f"Wine {index}",
        "h1": f"Wine {index}",
        "page_template_family": "product",
    }


def tanners_result() -> dict:
    """The audit's Tanners shape: 38 of 3,689 discovered URLs."""
    return {
        "website_url": "https://www.tanners-wines.co.uk/",
        "normalized_domain": "www.tanners-wines.co.uk",
        "pages_found": 3689,
        "pages_crawled": 38,
        "queued_remaining": 0,
        "crawled_pages": [_page(index) for index in range(38)],
        "crawl_timing": {
            "queue_exhausted": True,
            "failed_fetch_count": 0,
            "final_url_duplicates_deduped": 0,
            "sitemap_sources": [{
                "url": "https://www.tanners-wines.co.uk/sitemap.xml",
                "source": "robots_declared",
                "outcome": "urls",
                "loc_count": 3689,
            }],
        },
    }


def run_chain(result: dict) -> dict:
    review = run_review(result)
    review = apply_evidence_quality_gate(review, result)
    return attach_coverage_authority_evidence(review, result)


def build_fixture() -> dict:
    result = tanners_result()
    review = run_chain(result)
    scan = {
        "id": "scan_e2e",
        "project_id": "proj_e2e",
        "owner_user_id": "user_e2e",
        "request_id": "req_e2e",
        "attempt_count": 1,
        "started_at": "2026-08-22T03:00:00.000Z",
    }
    envelope = build_limited_envelope(scan, result, review, SIGNING_KEY)
    return {
        "_comment": (
            "Generated by scanner-api/tests/test_limited_result_end_to_end.py from the real "
            "scanner -> review -> worker chain. Regenerated and compared on every run, so it "
            "cannot drift from the pipeline it claims to represent."
        ),
        "scan_status": review["scan_status"],
        "release_gate_eligible": review["release_gate_eligible"],
        "score_is_provisional": review["score_is_provisional"],
        "coverage_state": review["site_fingerprint"]["coverage_assessment"]["state"],
        "envelope": {key: envelope[key] for key in ("version", "identity", "review")},
    }


def test_the_committed_fixture_still_matches_the_live_pipeline():
    """A fixture that can go stale proves nothing about today's code."""
    assert FIXTURE.exists(), f"missing {FIXTURE}"
    committed = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert build_fixture() == committed, (
        "the end-to-end fixture no longer matches the pipeline; regenerate it and "
        "review what changed rather than editing it by hand"
    )


def test_the_chain_ends_limited_and_never_authoritative():
    review = run_chain(tanners_result())

    assert review["release_gate_eligible"] is False
    assert review["score_is_provisional"] is True
    assert coverage_state_of(review) in LIMITED_COVERAGE_STATES


def test_the_chain_still_produces_evidence_worth_persisting():
    """The whole reason for the limited path: the findings are real."""
    review = run_chain(tanners_result())
    assert review.get("recommendations") or review.get("fixes")


def test_a_sufficient_crawl_never_produces_a_limited_envelope():
    sufficient = tanners_result()
    sufficient["pages_crawled"] = 150
    sufficient["pages_found"] = 5000
    sufficient["queued_remaining"] = 400
    sufficient["crawled_pages"] = [_page(index) for index in range(150)]
    review = run_chain(sufficient)

    assert review["release_gate_eligible"] is True
    assert coverage_state_of(review) not in LIMITED_COVERAGE_STATES


# ------------------------------------------- the remaining blueprint fixtures --


def _blocked_page(index: int) -> dict:
    return {
        "url": f"https://www.tanners-wines.co.uk/b{index}",
        "final_url": f"https://www.tanners-wines.co.uk/b{index}",
        "status_code": 429,
        "content_type": "text/html",
        "page_evidence_class": "failed_access",
        "word_count": 0,
        "title": "",
        "h1": "",
    }


def test_a_whole_site_challenge_with_no_useful_html_is_not_a_limited_result():
    """Zero usable evidence stays a failure, even though it produces a "fix".

    A wholly challenged crawl does emit one rate_limited_page item, so "has no
    findings" is not what keeps it off the limited path. What keeps it off is
    ordering: terminal_review_limitation is checked first and closes the scan as
    scan_access_limited before the limited branch is reached. Asserting the
    mechanism rather than the symptom, because the symptom is misleading here.
    """
    result = tanners_result()
    result["crawled_pages"] = [_blocked_page(index) for index in range(12)]
    result["pages_crawled"] = 12
    review = run_chain(result)

    assert review["release_gate_eligible"] is False
    limitation = terminal_review_limitation(review)
    assert limitation is not None, "a wholly challenged crawl must terminate, not persist"
    assert limitation["code"] == "scan_access_limited"


def test_partial_useful_html_with_a_material_challenge_is_limited_with_a_stated_scope():
    result = tanners_result()
    result["pages_found"] = 900
    result["pages_crawled"] = 30
    result["crawled_pages"] = [_page(index) for index in range(10)] + [_blocked_page(index) for index in range(20)]
    review = run_chain(result)

    assert review["release_gate_eligible"] is False
    assert review["score_is_provisional"] is True
    assert coverage_state_of(review) in LIMITED_COVERAGE_STATES
    # The customer is told what was and was not covered.
    assert review["limitation"], "a limited result must state its scope"


def test_an_incidental_challenge_on_a_sufficient_sample_stays_complete():
    """One rate-limited page in a healthy crawl is verification evidence, not a
    coverage failure -- and the unaffected scope stays explicit."""
    result = tanners_result()
    result["pages_found"] = 5000
    result["pages_crawled"] = 150
    result["queued_remaining"] = 400
    result["crawled_pages"] = [_page(index) for index in range(149)] + [_blocked_page(0)]
    review = run_chain(result)

    assert coverage_state_of(review) == "sufficient"
    assert review["release_gate_eligible"] is True
    assert review["limitation"] == "", "a sufficient scan states no coverage limitation"
